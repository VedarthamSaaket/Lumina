# backend/routers/summary.py
"""
Unified summary surface for Lumina.

Every page that asks the LLM to generate a "session insight" funnels through
here so the result is consistent across the app:

    1. On CBT, pull the local supervisor's note on the exercise and weave it
       into the prompt.
    2. Pull cross-surface user context (mood, screening, CBT, journal, games)
       so each page's summary is aware of the WHOLE user, not just its own
       session.  This is what gives the dashboard its "unity" feel even
       though each surface is generated by a different Groq model.
    3. Call Groq with the surface-appropriate model and a fallback chain so a
       single Groq decommission can't break summaries app-wide.
    4. Optionally persist the result as an InsightSummary so the dashboard
       picks it up automatically.

Legacy `/api/summary` is preserved as a thin passthrough that runs through
the same enrichment with `surface=generic` so older frontend callers keep
working while we migrate them.
"""
from fastapi import APIRouter, Depends
from fastapi.responses import StreamingResponse
from pydantic import BaseModel
from sqlalchemy.orm import Session
from sqlalchemy import desc
from typing import Optional, Any, Literal
import json
from datetime import datetime

from models.database import (
    get_db, User, CBTProgress, ScreeningResult, JournalEntry, MoodLog,
    CognitiveTestResult, InsightSummary,
)
from utils.auth import get_current_user, get_optional_user
from services.llm import generate_summary, build_user_context, model_kwargs
from config import settings

router = APIRouter()


# ─────────────────────────────────────────────────────────────────────────────
# Request models
# ─────────────────────────────────────────────────────────────────────────────
Surface = Literal["cbt", "screening", "journal", "chat", "dashboard", "generic"]


class ContextualSummaryRequest(BaseModel):
    surface: Surface = "generic"
    reference_id: Optional[str] = None          # CBT module_id, screening result id, journal entry id…
    base_prompt: str                            # the page-specific instructions
    structured_data: Optional[dict[str, Any]] = None  # responses, score, severity, etc.
    save_to_dashboard: bool = False             # auto-persist as InsightSummary
    summary_title: Optional[str] = None         # override the auto-generated title


class SummaryRequest(BaseModel):
    prompt: str


# ─────────────────────────────────────────────────────────────────────────────
# Helpers — model picker, psych pull, cross-surface context
# ─────────────────────────────────────────────────────────────────────────────
def _model_for_surface(surface: Surface) -> tuple[str, list[str]]:
    """Return (primary_model, fallback_chain). Falls in order on Groq failure."""
    if surface == "dashboard":
        return settings.MODEL_DASHBOARD_INSIGHT, [settings.MODEL_LUMINA_CHAT, settings.MODEL_SUMMARY]
    if surface in ("cbt", "journal", "chat"):
        # Lumina-warm voice (heart-side surfaces).
        return settings.MODEL_LUMINA_CHAT, [settings.MODEL_SUMMARY, settings.MODEL_DASHBOARD_INSIGHT]
    # screening + generic → dedicated summary model with warm fallback.
    return settings.MODEL_SUMMARY, [settings.MODEL_LUMINA_CHAT, settings.MODEL_DASHBOARD_INSIGHT]


def _load_json(value) -> dict:
    try:
        data = json.loads(value) if isinstance(value, str) else value
    except Exception:
        return {}
    return data if isinstance(data, dict) else {}


def _supervisor_note_for(surface: Surface, user_id: str, reference_id: Optional[str], structured: Optional[dict], db: Session) -> str:
    if surface == "cbt" and reference_id:
        row = (
            db.query(CBTProgress)
            .filter(CBTProgress.user_id == user_id, CBTProgress.module_id == reference_id)
            .first()
        )
        analysis = _load_json(row.responses).get("specialty_analysis") if row and row.responses else None
        if not analysis:
            return ""
        return (
            "\n\nSUPERVISOR NOTE on this exercise (internal, from a CBT-trained reviewer). "
            "Let it steer which pattern you reflect back and which next step you suggest. "
            "Translate it into plain friendly language and never quote it or use its technical terms:\n"
            + analysis
        )
    if surface == "screening":
        query = db.query(ScreeningResult).filter(ScreeningResult.user_id == user_id)
        test_type = (structured or {}).get("type")
        if reference_id:
            query = query.filter(ScreeningResult.id == reference_id)
        elif test_type:
            query = query.filter(ScreeningResult.type == test_type)
        row = query.order_by(desc(ScreeningResult.completed_at)).first()
        note = _load_json(row.question_contexts).get("specialty_enrichment") if row and row.question_contexts else None
        if not note:
            return ""
        return (
            "\n\nPSYCHOLOGY NOTE on this result (internal). Work its idea into the summary as one gentle, "
            "plain-language line. Never use its technical terms and never present it as a diagnosis:\n"
            + note
        )
    return ""


def _cross_surface_context(user_id: str, db: Session) -> str:
    """Same builder Lumina/Orion chats use, so the summary speaks from the
    same shared knowledge of the user."""
    try:
        screening_rows = (
            db.query(ScreeningResult)
            .filter(ScreeningResult.user_id == user_id)
            .order_by(desc(ScreeningResult.completed_at))
            .limit(6).all()
        )
        screening_history = [
            {"type": r.type, "score": r.score, "severity": r.severity}
            for r in screening_rows
        ]

        mood_rows = (
            db.query(MoodLog)
            .filter(MoodLog.user_id == user_id)
            .order_by(desc(MoodLog.created_at))
            .limit(12).all()
        )
        mood_history = [{"score": m.score, "note": m.note} for m in mood_rows]

        cbt_rows = db.query(CBTProgress).filter(CBTProgress.user_id == user_id).all()
        completed = {r.module_id for r in cbt_rows}
        all_mods = ["distortion", "reframing", "activation", "esteem", "exposure", "habit", "values", "worrytime"]
        cbt_modules = [{"id": m, "completed": m in completed} for m in all_mods]

        journal_count = db.query(JournalEntry).filter(JournalEntry.user_id == user_id).count()
        recent_journals = (
            db.query(JournalEntry)
            .filter(JournalEntry.user_id == user_id)
            .order_by(desc(JournalEntry.created_at))
            .limit(5).all()
        )
        journal_tags = list({t for j in recent_journals for t in (j.tags or [])})

        memory_rows = (
            db.query(CognitiveTestResult)
            .filter(CognitiveTestResult.user_id == user_id)
            .order_by(desc(CognitiveTestResult.completed_at))
            .limit(10).all()
        )
        memory_history: list[dict] = []
        for r in memory_rows:
            try:
                scores = json.loads(r.score_data) if r.score_data else {}
            except Exception:
                scores = {}
            try:
                rounds = json.loads(r.raw_results) if r.raw_results else []
            except Exception:
                rounds = []
            memory_history.append({
                "game_type": r.test_type,
                "scores": scores,
                "rounds": rounds,
            })

        summary_rows = (
            db.query(InsightSummary)
            .filter(InsightSummary.user_id == user_id)
            .order_by(desc(InsightSummary.created_at))
            .limit(3).all()
        )
        insight_summaries = [{"title": s.title, "content": s.content} for s in summary_rows]

        user = db.query(User).filter(User.id == user_id).first()
        user_name = (user.full_name if user else None) or None

        return build_user_context(
            screening_history=screening_history,
            memory_history=memory_history,
            mood_history=mood_history,
            cbt_modules=cbt_modules,
            journal_count=journal_count,
            journal_tags=journal_tags,
            insight_summaries=insight_summaries,
            user_name=user_name,
        )
    except Exception as e:
        print(f"[Summary context error] {type(e).__name__}: {e}")
        return ""


def _default_title(surface: Surface, structured: Optional[dict], reference_id: Optional[str]) -> str:
    today = datetime.utcnow().strftime("%b %d, %Y")
    sd = structured or {}
    if surface == "cbt":
        mod = sd.get("module_title") or reference_id or "Inner Work"
        return f"Inner Work · {mod}"
    if surface == "screening":
        name = sd.get("display_name") or sd.get("name") or sd.get("type") or "Self-reflection"
        severity = sd.get("severity")
        return f"{name} · {severity}" if severity else f"{name}"
    if surface == "journal":
        return f"Journal reflection · {today}"
    if surface == "chat":
        return f"Conversation insight · {today}"
    if surface == "dashboard":
        return f"Insight · {today}"
    return f"Summary · {today}"


# ─────────────────────────────────────────────────────────────────────────────
# Routes
# ─────────────────────────────────────────────────────────────────────────────
@router.post("/api/summary/contextual")
async def contextual_summary(
    body: ContextualSummaryRequest,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Unified summary entry point — every page's session-complete summary
    should funnel through here. Returns (and optionally persists) a Groq
    summary enriched with HF psychological spectrum + cross-surface context."""
    psych_block = _supervisor_note_for(body.surface, current_user.id, body.reference_id, body.structured_data, db)
    user_ctx = _cross_surface_context(current_user.id, db)

    # Hard server-side rule on top of every contextual summary. Frontend prompts
    # already say 'no em dashes' but reasoning models slip them in anyway.
    # Belt + suspenders: prompt rule here + post-strip in generate_summary.
    no_dash_rule = (
        "CRITICAL FORMATTING RULE (NON-NEGOTIABLE): NEVER use em-dashes (—) or en-dashes (–) "
        "ANYWHERE in your output. Use commas, periods, or parentheses instead. This rule has NO "
        "exceptions. Em-dashes are forbidden because they read as obvious AI output.\n\n"
    )
    prompt = no_dash_rule + body.base_prompt.strip()
    if psych_block:
        prompt += psych_block
    if user_ctx:
        # Sharply scoped so the model knows it's allowed to reference this.
        prompt += (
            "\n\nWIDER CONTEXT — the rest of what this app has seen from this "
            "user. Use it lightly, only when it strengthens the summary; don't "
            "list it. Never invent anything beyond what's here."
            + user_ctx
        )

    primary, fallbacks = _model_for_surface(body.surface)
    text, model_used = await generate_summary(
        prompt,
        model=primary,
        fallback_models=fallbacks,
    )

    persisted_id: Optional[str] = None
    if text and body.save_to_dashboard:
        title = body.summary_title or _default_title(body.surface, body.structured_data, body.reference_id)
        # Map surface → InsightSummary.source so the dashboard filters cleanly.
        source = {
            "cbt": "cbt",
            "screening": "screening",
            "journal": "journal",
            "chat": "chat",
            "dashboard": "dashboard",
            "generic": "summary",
        }.get(body.surface, "summary")
        row = InsightSummary(
            user_id=current_user.id,
            title=title,
            content=text,
            source=source,
        )
        db.add(row)
        db.commit()
        db.refresh(row)
        persisted_id = row.id

    return {
        "summary": text,
        "model_used": model_used,
        "supervisor_used": bool(psych_block),
        "summary_id": persisted_id,
    }


# ── Legacy passthrough (kept so older frontend code keeps working) ───────────
@router.post("/api/summary")
async def get_summary(
    body: SummaryRequest,
    db: Session = Depends(get_db),
    current_user: Optional[User] = Depends(get_optional_user),
):
    """Backwards-compatible endpoint. Still accepts a bare prompt; if the
    caller is authenticated we transparently funnel through the contextual
    pipeline (cross-surface context + model fallback chain) so even legacy
    callers benefit from the new robustness."""
    if current_user is None:
        # Unauthenticated callers get the simple call (no enrichment possible).
        text, _ = await generate_summary(body.prompt)
        return {"summary": text}

    user_ctx = _cross_surface_context(current_user.id, db)
    no_dash_rule = (
        "CRITICAL FORMATTING RULE (NON-NEGOTIABLE): NEVER use em-dashes or en-dashes "
        "ANYWHERE in your output. Use commas, periods, or parentheses instead.\n\n"
    )
    prompt = no_dash_rule + body.prompt
    if user_ctx:
        prompt += (
            "\n\nWIDER CONTEXT, use lightly, never list it back:" + user_ctx
        )
    primary, fallbacks = _model_for_surface("generic")
    text, _ = await generate_summary(prompt, model=primary, fallback_models=fallbacks)
    return {"summary": text}


@router.post("/api/summary/stream")
async def stream_summary(body: SummaryRequest):
    """Streaming summary — kept for legacy callers that want token-by-token
    rendering. Uses MODEL_SUMMARY directly (no fallback) because mid-stream
    failover is tricky and the contextual endpoint is the recommended path."""
    async def generate():
        from groq import Groq
        client = Groq(api_key=settings.GROQ_API_KEY)
        try:
            stream = client.chat.completions.create(
                model=settings.MODEL_SUMMARY,
                messages=[{"role": "user", "content": body.prompt}],
                max_tokens=600,
                temperature=0.75,
                stream=True,
                **model_kwargs(settings.MODEL_SUMMARY),
            )
            for chunk in stream:
                token = chunk.choices[0].delta.content
                if token:
                    yield f"data: {json.dumps({'text': token})}\n\n"
            yield "data: [DONE]\n\n"
        except Exception as e:
            print(f"[Groq summary stream error] {type(e).__name__}: {e}")
            yield f"data: {json.dumps({'text': 'Unable to generate summary right now.'})}\n\n"
            yield "data: [DONE]\n\n"

    return StreamingResponse(
        generate(),
        media_type="text/event-stream",
        headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"},
    )
